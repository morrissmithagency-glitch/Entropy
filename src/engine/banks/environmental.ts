const t = (level: Level, prompt: string, answer: string, wrong: string[], visual?: Visual): BankQuestion => ({
  type: 'choice',
  level,
  prompt,
  options: [answer, ...wrong].map((l) => ({ id: l, label: l })),
  answer,
  ...(visual ? { visual } : {}),
})

